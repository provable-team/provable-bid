from enum import Enum
from typing import Annotated, TypeAlias

from ...core import open_enum_validator


class Code(str, Enum):
    VALIDATION_ERROR = "VALIDATION_ERROR"
    INVALID_WEBHOOK = "INVALID_WEBHOOK"
    UNAUTHENTICATED = "UNAUTHENTICATED"
    FORBIDDEN = "FORBIDDEN"
    NOT_FOUND = "NOT_FOUND"
    INVALID_STATE = "INVALID_STATE"
    DEADLINE_PASSED = "DEADLINE_PASSED"
    IDEMPOTENCY_CONFLICT = "IDEMPOTENCY_CONFLICT"
    DECISION_LOCKED = "DECISION_LOCKED"
    DELIVERY_LOCKED = "DELIVERY_LOCKED"
    DUPLICATE_SUBMISSION = "DUPLICATE_SUBMISSION"
    PAYMENT_NOT_READY = "PAYMENT_NOT_READY"
    PAYLOAD_TOO_LARGE = "PAYLOAD_TOO_LARGE"
    TERMS_MISMATCH = "TERMS_MISMATCH"
    PAYMENT_CAPABILITY_UNAVAILABLE = "PAYMENT_CAPABILITY_UNAVAILABLE"
    RATE_LIMITED = "RATE_LIMITED"
    PROVIDER_UNAVAILABLE = "PROVIDER_UNAVAILABLE"
    INTERNAL_ERROR = "INTERNAL_ERROR"
    OPERATOR_REQUIRED = "OPERATOR_REQUIRED"

    __str__ = str.__str__


CodeOrStr: TypeAlias = Annotated[Code | str, open_enum_validator(Code)]
